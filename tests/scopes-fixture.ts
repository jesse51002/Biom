/** A vault's files WITHOUT A CLOCK. `Child.created` is read off the directory,
 *  and a scratch copy's directories are made on every run, so a golden holding
 *  it would hold the time the test ran. The contract has the field absent
 *  where the store keeps no clock, which is this. */
export function clockless<T extends object>(files: T): T {
  const out = { ...files } as T & { created?: unknown };
  delete out.created;
  return out;
}

