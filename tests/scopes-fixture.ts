/** JSON with every object's keys sorted, at every depth: one value, one text. */
export function stable(v: unknown): string {
  if (v === undefined) return "undefined";
  if (v === null || typeof v !== "object") return JSON.stringify(v);
  if (Array.isArray(v)) return `[${v.map(stable).join(",")}]`;
  const o = v as Record<string, unknown>;
  return `{${Object.keys(o).sort().map((k) => `${JSON.stringify(k)}:${stable(o[k])}`).join(",")}}`;
}

/** `stable`, indented, for a golden a person may have to read. */
export const pretty = (v: unknown): string => `${JSON.stringify(JSON.parse(stable(v)), null, 2)}\n`;

export const sha = (text: string): string => createHash("sha256").update(text).digest("hex");

/* ── the goldens ─────────────────────────────────────────────────────────── */

interface Manifest {
  capturedFrom: string;
  rule: string;
  files: Record<string, string>;
}

const MANIFEST = join(GOLDEN, "manifest.json");
const RULE =
  "Captured from the code before the fourteenth contracts edit and never regenerated by the change it holds. " +
  "GOLDEN_CAPTURE=1 writes a missing golden and never overwrites one.";

function manifest(): Manifest {
  if (!existsSync(MANIFEST)) return { capturedFrom: CAPTURED_FROM, rule: RULE, files: {} };
  return JSON.parse(readFileSync(MANIFEST, "utf8")) as Manifest;
}

/**
 * THE ONE DOOR TO A GOLDEN. Comparing, it answers the golden's text and throws
 * if the file is missing or its bytes are not the ones the manifest recorded.
 * Capturing, a missing golden is written from `actual` and recorded, and one
 * that is there is left exactly as it is and answered — so a capture run is
 * also a comparison run for everything it did not have to write.
 */
export function golden(rel: string, actual: string): string {
  const at = join(GOLDEN, rel);
  const m = manifest();
  if (!existsSync(at)) {
    if (!capturing()) throw new Error(`no golden at ${rel} — goldens are captured once, before the change, with GOLDEN_CAPTURE=1`);
    mkdirSync(dirname(at), { recursive: true });
    writeFileSync(at, actual, "utf8");
    m.files[rel] = sha(actual);
    const files = Object.fromEntries(Object.entries(m.files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
    writeFileSync(MANIFEST, `${JSON.stringify({ ...m, files }, null, 2)}\n`, "utf8");
    return actual;
  }
  const text = readFileSync(at, "utf8");
  const want = m.files[rel];
  if (want === undefined) throw new Error(`the golden ${rel} is not in manifest.json — it was not captured by the capture run`);
  if (sha(text) !== want) throw new Error(`the golden ${rel} was changed after it was captured — goldens are never regenerated by the change they hold`);
  return text;
}

/** A golden that is only ever READ, capturing or not: one captured by the
 *  other half of the suite, which this half compares with and never writes. */
export function held(rel: string): string {
  const at = join(GOLDEN, rel);
  if (!existsSync(at)) throw new Error(`no golden at ${rel} — it is captured by the other half of the suite`);
  const text = readFileSync(at, "utf8");
  if (sha(text) !== manifest().files[rel]) throw new Error(`the golden ${rel} was changed after it was captured`);
  return text;
}

/* ── the wire ────────────────────────────────────────────────────────────── */

/** The part of a `page.read` answer the runtime draws and projects from. */
export interface Wire {
  id: string;
  name: string;
  plugin: string;
  variables: Variables;
  sections: Page["sections"];
}

export const wireOf = (page: Page): Wire => ({
  id: page.id,
  name: page.name,
  plugin: page.plugin,
  variables: page.variables,
  sections: page.sections,
});

/**
 * THE SAME PAGE, AS THE FOURTEENTH EDIT SPELLS IT: each section's `vars` its
 * own `variables:`, each part's (list items included) its content's own, `{}`
 * where it has none. Derived from the document each `DrawnSection` carries in
 * `source`, never from the merged values, so it cannot inherit a merge.
 */
export function ownWire(wire: Wire): Wire {
  const sections = wire.sections.map((s) => {
    const source = s.source;
    const parts: Record<string, unknown> = {};
    for (const [slot, part] of Object.entries(s.parts)) {
      const held = source.parts?.[slot];
      if (part.kind === "list") {
        const items = (Array.isArray(held) ? held : []).map((one) => contentOf(one)).filter((c) => c !== null);
        if (items.length !== part.items.length) throw new Error(`${wire.id} ${s.name}.${slot}: the list's items do not line up with its document`);
        parts[slot] = { ...part, items: part.items.map((item, i) => ownPart(item, items[i]?.variables)) };
      } else {
        parts[slot] = ownPart(part, Array.isArray(held) ? undefined : contentOf(held)?.variables);
      }
    }
    return { ...s, vars: varsOf(source.variables), parts } as typeof s;
  });
  return { ...wire, sections };
}

function ownPart<P extends { kind: string }>(part: P, own: Variables | undefined): P {
  return "vars" in part ? { ...part, vars: varsOf(own) } : part;
}

/* ── the real runtime, over a stand-in document ──────────────────────────── */

/** What one mount was handed. `via` says which door: a `slot`, a list `item`,
 *  a `data-g-plugin` `node`, or a section `script`. */
export interface Mount {
  via: "slot" | "item" | "node" | "script";
  section: string;
  part: string | null;
  item: number | null;
  node: string | null;
  ctx: unknown;
  content: unknown;
}

export interface DrawnRecord {
  name: string;
  /** The section's markup after `{{name}}` was resolved, as a digest. */
  markup: string;
  mounts: Mount[];
}

const VOID = new Set(["area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"]);

/**
 * A STAND-IN FOR THE BOX'S DOCUMENT: elements, attributes, a tree, and the
 * handful of calls `sections.js` makes — no layout, no text nodes, no events.
 * Enough to run the real `draw` and `fillSlots` in bun, so a change to either
 * is exercised without a browser; `e2e/scopes-dom.e2e.ts` is the real browser.
 */
class El {
  tagName: string;
  attrs = new Map<string, string>();
  kids: El[] = [];
  parent: El | null = null;
  own = "";
  content: El | null = null;
  constructor(tag: string, private readonly doc: FakeDoc) {
    this.tagName = tag.toLowerCase();
    if (this.tagName === "template") this.content = new El("#fragment", doc);
  }
  get id(): string {
    return this.attrs.get("id") ?? "";
  }
  set id(v: string) {
    this.attrs.set("id", v);
  }
  setAttribute(n: string, v: unknown): void {
    this.attrs.set(n.toLowerCase(), String(v));
  }
  getAttribute(n: string): string | null {
    return this.attrs.get(n.toLowerCase()) ?? null;
  }
  hasAttribute(n: string): boolean {
    return this.attrs.has(n.toLowerCase());
  }
  removeAttribute(n: string): void {
    this.attrs.delete(n.toLowerCase());
  }
  get attributes(): { name: string; value: string }[] {
    return [...this.attrs].map(([name, value]) => ({ name, value }));
  }
  get dataset(): Record<string, string> {
    const out: Record<string, string> = {};
    for (const [n, v] of this.attrs) {
      if (n.startsWith("data-")) out[n.slice(5).replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())] = v;
    }
    return out;
  }
  get textContent(): string {
    return this.own + this.kids.map((k) => k.textContent).join("");
  }
  set textContent(v: string) {
    for (const k of this.kids) k.parent = null;
    this.kids = [];
    this.own = String(v ?? "");
  }
  set innerHTML(html: string) {
    this.doc.markup.push(html);
    const into = this.content ?? this;
    into.textContent = "";
    parseInto(into, html, this.doc);
  }
  appendChild(c: El): El {
    if (c.tagName === "#fragment") {
      for (const k of [...c.kids]) this.appendChild(k);
      return c;
    }
    c.remove();
    c.parent = this;
    this.kids.push(c);
    // A script appended to the document runs, which is how a section script's
    // bindings are claimed — so appending one here claims them.
    if (c.tagName === "script") this.doc.ran(c);
    return c;
  }
  replaceChildren(...nodes: El[]): void {
    this.textContent = "";
    for (const n of nodes) this.appendChild(n);
  }
  remove(): void {
    if (this.parent === null) return;
    const at = this.parent.kids.indexOf(this);
    if (at >= 0) this.parent.kids.splice(at, 1);
    this.parent = null;
  }
  contains(n: El | null): boolean {
    for (let at = n; at !== null; at = at.parent) if (at === this) return true;
    return false;
  }
  querySelectorAll(selector: string): El[] {
    const test = matcher(selector);
    const out: El[] = [];
    const walk = (el: El): void => {
      for (const k of el.kids) {
        if (test(k)) out.push(k);
        walk(k);
      }
    };
    walk(this);
    return out;
  }
  querySelector(selector: string): El | null {
    return this.querySelectorAll(selector)[0] ?? null;
  }
}

/** `[attr]`, `[attr="value"]` and a bare tag: every selector `sections.js` asks. */
function matcher(selector: string): (el: El) => boolean {
  const attr = /^\[([\w-]+)(?:="([^"]*)")?\]$/.exec(selector.trim());
  if (attr) return (el) => el.attrs.has(attr[1] as string) && (attr[2] === undefined || el.attrs.get(attr[1] as string) === attr[2]);
  if (/^[a-z][\w-]*$/i.test(selector.trim())) return (el) => el.tagName === selector.trim().toLowerCase();
  throw new Error(`the stand-in document cannot answer the selector ${selector}`);
}

function attrsInto(el: El, text: string): void {
  const re = /([^\s=/"'>]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g;
  for (let m = re.exec(text); m !== null; m = re.exec(text)) {
    el.attrs.set((m[1] as string).toLowerCase(), m[2] ?? m[3] ?? m[4] ?? "");
  }
}

/** Elements and their nesting, and a script's or a style's text; nothing else
 *  is kept. Comments go first, so markup quoted in one is not an element. */
function parseInto(root: El, html: string, doc: FakeDoc): void {
  const src = html.replace(/<!--[\s\S]*?-->/g, "");
  const re =
    /<(script|style)\b((?:[^>"']|"[^"]*"|'[^']*')*)>([\s\S]*?)<\/\1\s*>|<\/([A-Za-z][\w:-]*)\s*>|<([A-Za-z][\w:-]*)((?:[^>"']|"[^"]*"|'[^']*')*?)(\/?)>/g;
  const stack: El[] = [root];
  for (let m = re.exec(src); m !== null; m = re.exec(src)) {
    const top = stack[stack.length - 1] as El;
    if (m[1] !== undefined) {
      const el = new El(m[1], doc);
      attrsInto(el, m[2] ?? "");
      el.own = m[3] ?? "";
      el.parent = top;
      top.kids.push(el);
      continue;
    }
    if (m[4] !== undefined) {
      const tag = m[4].toLowerCase();
      for (let i = stack.length - 1; i > 0; i--) {
        if ((stack[i] as El).tagName === tag) {
          stack.length = i;
          break;
        }
      }
      continue;
    }
    const el = new El(m[5] as string, doc);
    attrsInto(el, m[6] ?? "");
    el.parent = top;
    top.kids.push(el);
    if (m[7] !== "/" && !VOID.has(el.tagName)) stack.push(el);
  }
}

class FakeDoc {
  markup: string[] = [];
  constructor(private readonly onScript: (n: number) => void) {}
  createElement(tag: string): El {
    return new El(tag, this);
  }
  ran(script: El): void {
    const n = /__gRuntime\.claim\((\d+)\)/.exec(script.own);
    if (n) this.onScript(Number(n[1]));
  }
}

const SECTIONS_JS = join(import.meta.dir, "..", "guest", "runtime", "sections.js");

/**
 * DRAW A PAGE WITH THE REAL `sections.js` and answer every mount it made.
 *
 * The runtime is evaluated fresh for each page, over the stand-in document,
 * with a registry in which every plugin and every part kind is a recorder: it
 * draws nothing and keeps what it was handed. `pageVars` is what `boot.js`
 * hands the draw, the answer's `variables`.
 */
export function drawnMounts(wire: Wire): { sections: DrawnRecord[]; said: string[] } {
  const rt: Record<string, unknown> = {};
  const said: string[] = [];
  let current: { mounts: Mount[]; items: Map<string, number> } = { mounts: [], items: new Map() };
  const doc = new FakeDoc((n) => {
    const got = (rt.claim as (n: number) => { ctx: { section: string; vars: unknown } } | null)(n);
    if (got) current.mounts.push({ via: "script", section: got.ctx.section, part: null, item: null, node: null, ctx: got.ctx.vars, content: null });
  });
  const recorder = (id: string) => ({
    id,
    mount(node: El, content: unknown, ctx: { section: string; part: string | null; vars: unknown }) {
      let via: Mount["via"] = "slot";
      let item: number | null = null;
      if (ctx.part === null) via = "node";
      else if (node.parent === null) {
        // A list item's holder is mounted before it is put in the slot.
        via = "item";
        const key = `${ctx.section} ${ctx.part}`;
        item = current.items.get(key) ?? 0;
        current.items.set(key, item + 1);
      }
      current.mounts.push({
        via,
        section: ctx.section,
        part: ctx.part,
        item,
        node: via === "node" ? node.getAttribute("data-g-plugin") : null,
        ctx: ctx.vars,
        content,
      });
    },
  });
  rt.plugins = {
    forKind: (kind: string) => recorder(`kind:${kind}`),
    get: (id: string) => recorder(id),
    reach: (id: string) => recorder(id),
    ids: () => [],
  };
  rt.effects = { onTeardown() {}, remember() {}, disposeAll() {} };
  rt.report = (message: string) => void said.push(message);

  const glob = globalThis as Record<string, unknown>;
  const was = glob.__gRuntime;
  glob.__gRuntime = rt;
  try {
    new Function("document", "CSS", readFileSync(SECTIONS_JS, "utf8"))(doc, {
      escape: (s: string) => s.replace(/[^\w-]/g, (c) => `\\${c}`),
    });
  } finally {
    glob.__gRuntime = was;
  }
  const sections = rt.sections as { draw: (drawn: unknown, env: unknown) => unknown };

  const root = doc.createElement("main");
  const env = { page: wire.id, root, pageVars: wire.variables || {}, call: () => Promise.resolve(null), dress() {} };
  const out: DrawnRecord[] = [];
  for (const section of wire.sections) {
    current = { mounts: [], items: new Map() };
    doc.markup = [];
    sections.draw(section, env);
    out.push({ name: section.name, markup: sha(doc.markup[0] ?? ""), mounts: current.mounts });
  }
  // Round-tripped, so what is compared is what a golden can hold.
  return JSON.parse(JSON.stringify({ sections: out, said })) as { sections: DrawnRecord[]; said: string[] };
}

