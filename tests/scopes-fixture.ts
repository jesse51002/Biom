// test file, a helper `scopes-equivalence.test.ts` and `e2e/scopes-dom.e2e.ts`
// import (named without `.test.` so `bun test` walks past it).
//
// WHAT IT HOLDS STILL. The fourteenth edit narrows two frozen fields:
// `DrawnSection.vars` and a `Part`'s `vars` carry the entry's OWN variables,
// where they carried the three scopes already merged. The page's values then
// travel once, in `Page.variables`, instead of once per section and once per
// part — which is what made a 649-section page 65 MB on the wire. Everything a
// page, a section script or a plugin is handed must come out the same, and
// "the same" is not argued here: it is captured, from the code as it stood
// BEFORE the change, and every later build is compared with that capture.
//
// THREE GOLDEN SETS, under `fixtures/scopes-golden/`:
//
//   - `scopes.json` — for every page of the corpus, every mount the runtime
//     makes (a slot, a list item, a `data-g-plugin` node, a section script) and
//     the scope and content it is handed, drawn by the REAL `sections.js` over a
//     stand-in document (below); plus `wire/`, the answer the old server gave,
//     so a new runtime can be shown drawing it the same.
//   - `projection/` and `mirror/` — every page's projected markdown and its
//     mirror file, byte for byte.
//   - `dom/` — every page's drawn `#g-page`, from a real browser, normalised.
//
// THE RULE THAT MAKES THEM WORTH ANYTHING: a golden is captured once and never
// regenerated by the change it holds. `GOLDEN_CAPTURE=1` writes a golden that
// is MISSING and never overwrites one that is there; `manifest.json` holds
// every file's digest, and a comparison refuses a golden whose bytes no longer
// match it. Regenerating one is therefore a deleted file and an edited manifest
// in the diff, which is exactly what a reviewer should be made to see.
//
// Every page, word, number and identity in the corpus is invented; the frozen
// copies of the shipped `vault/base/` pages and `vault/design/` are the
// framework's own words, copied as they stood when the goldens were taken.

