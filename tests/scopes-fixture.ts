/** The shape measured on the owner's Talks page: 649 sections, each a child's
 *  row drawn with the default section, under about 95 KB of page variables. */
export const TALKS = Object.freeze({ id: "home/Talks", sections: 649, varBytes: 95_000 });

/**
 * WRITE A VAULT HOLDING ONE PAGE THE SHAPE OF TALKS, deterministically: a root,
 * the page, and 649 children, each held by a section of its own. Its own vault
 * rather than the corpus's, so the corpus's root does not grow a child row.
 */
export function inventTalks(vault: string): void {
  const home = join(vault, "pages", "home");
  mkdirSync(home, { recursive: true });
  writeFileSync(
    join(home, "content.yaml"),
    ["name: Invented Root", "uid: scopestalksroot01", "plugin: biom-doc", "contents:", "  - name: body", "    parts:", "      body: An invented root.", ""].join("\n"),
    "utf8",
  );
  const talks = join(home, "children", "Talks");
  mkdirSync(talks, { recursive: true });
  const rooms = ["North", "South", "East", "West", "Upper", "Lower"];
  const speakers: string[] = [];
  for (let i = 0; speakers.join("").length < TALKS.varBytes - 2_000; i++) {
    speakers.push(`Invented Speaker ${String(i).padStart(4, "0")} of the ${rooms[i % rooms.length]} room, on a subject nobody has given, for about forty minutes`);
  }
  const lines = [
    "name: Talks",
    "uid: scopestalks01",
    "plugin: biom-doc",
    "variables:",
    "  venue: The Invented Hall",
    "  year: 2026",
    "  speakers:",
    ...speakers.map((s) => `    - ${s}`),
    "contents:",
    "  - name: intro",
    "    parts:",
    "      body: Every talk at {{venue}} in {{year}}, invented.",
  ];
  for (let i = 1; i <= TALKS.sections; i++) {
    const seg = `Talk_${String(i).padStart(3, "0")}`;
    lines.push(`  - name: "@page-${seg}"`, "    parts:", "      body:", "        type: child", `        data: ${seg}`);
    const dir = join(talks, "children", seg);
    mkdirSync(dir, { recursive: true });
    writeFileSync(
      join(dir, "content.yaml"),
      [`name: Talk ${i}`, `uid: scopestalk${String(i).padStart(4, "0")}`, "plugin: biom-doc", "contents:", "  - name: body", "    parts:", `      body: Invented talk ${i}, at {{venue}}.`, ""].join("\n"),
      "utf8",
    );
  }
  lines.push("");
  writeFileSync(join(talks, "content.yaml"), lines.join("\n"), "utf8");
}

/** Every `html` string an answer carries — section markup, an html part's, a
 *  child's own drawing — in bytes. What the fourteenth edit is about is the
 *  rest of the answer, so the size check is taken without it. */
export function markupBytes(wire: Wire): number {
  let n = 0;
  const len = (s: unknown): number => (typeof s === "string" ? Buffer.byteLength(JSON.stringify(s)) : 0);
  const part = (p: Record<string, unknown>): void => {
    n += len(p.html);
    const draw = p.draw as { html?: unknown } | undefined;
    if (draw) n += len(draw.html);
    if (Array.isArray(p.items)) for (const i of p.items) part(i as Record<string, unknown>);
  };
  for (const s of wire.sections) {
    n += len(s.html);
    for (const p of Object.values(s.parts)) part(p as unknown as Record<string, unknown>);
  }
  return n;
}
